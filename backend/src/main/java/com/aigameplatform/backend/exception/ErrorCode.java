package com.aigameplatform.backend.exception;

import org.springframework.http.HttpStatus;

/** Bảng mã lỗi dùng chung theo REST API Contract v1.0.0. */
public enum ErrorCode {
    VALIDATION_ERROR(HttpStatus.BAD_REQUEST),
    UNAUTHORIZED(HttpStatus.UNAUTHORIZED),
    FORBIDDEN(HttpStatus.FORBIDDEN),
    NOT_FOUND(HttpStatus.NOT_FOUND),
    GAME_HAS_PLAY_HISTORY(HttpStatus.CONFLICT),
    NARRATION_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),
    SHARE_CODE_UNAVAILABLE(HttpStatus.INTERNAL_SERVER_ERROR),
    CONFLICT(HttpStatus.CONFLICT),
    FILE_TOO_LARGE_OR_INVALID_FORMAT(HttpStatus.UNPROCESSABLE_ENTITY),
    LESSON_CLARIFICATION_REQUIRED(HttpStatus.UNPROCESSABLE_ENTITY),
    UNSAFE_CONTENT(HttpStatus.UNPROCESSABLE_ENTITY),
    CURRICULUM_EVIDENCE_NOT_FOUND(HttpStatus.UNPROCESSABLE_ENTITY),
    CURRICULUM_CLARIFICATION_REQUIRED(HttpStatus.UNPROCESSABLE_ENTITY),
    GENERATED_CONTENT_UNVERIFIED(HttpStatus.UNPROCESSABLE_ENTITY),
    GENERATION_SCOPE_UNSUPPORTED(HttpStatus.UNPROCESSABLE_ENTITY),
    CURRICULUM_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),
    SCENE_IMAGE_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),
    SERVICE_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),
    LESSON_PROCESSING_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),
    INPUT_SAFETY_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),
    AI_GENERATION_TIMEOUT(HttpStatus.GATEWAY_TIMEOUT),
    RATE_LIMITED(HttpStatus.TOO_MANY_REQUESTS),
    ACCOUNT_LOCKED(HttpStatus.FORBIDDEN),
    LOGIN_TEMPORARILY_LOCKED(HttpStatus.TOO_MANY_REQUESTS),
    INTERNAL_ERROR(HttpStatus.INTERNAL_SERVER_ERROR);

    private final HttpStatus status;

    ErrorCode(HttpStatus status) {
        this.status = status;
    }

    public HttpStatus getStatus() {
        return status;
    }
}
